// Run from android/: node tools/check_android_rebrand.js
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const oldBrand = /Apollo|Sunshine|Moonlight|Vibepollo|Artemis|Artemistics|Sunsihne/i;
const withoutDependencies = text => text
    .replace(/https?:\/\/[^\s<>"']+/g, '')
    .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, '')
    .replace(/Moonlight Internet Hosting Tool/g, '');

let checked = 0;
for (const folder of fs.readdirSync(path.join(root, 'app/src/main/res'))) {
    if (!/^values(?:-|$)/.test(folder)) continue;
    const file = `app/src/main/res/${folder}/strings.xml`;
    if (!fs.existsSync(path.join(root, file))) continue;
    for (const [, , body] of read(file).matchAll(/(<string\b[^>]*>)([\s\S]*?)<\/string>/g)) {
        assert(!oldBrand.test(withoutDependencies(body)), `${file}: old product name`);
    }
    checked++;
}
for (const locale of ['de', 'en-US']) {
    for (const name of ['title.txt', 'short_description.txt', 'full_description.txt']) {
        const file = `fastlane/metadata/android/${locale}/${name}`;
        assert(!oldBrand.test(withoutDependencies(read(file))), `${file}: old product name`);
    }
}
const gradle = read('app/build.gradle');
assert(gradle.includes('applicationId "com.flugel.nous"'));
assert(gradle.includes("namespace 'com.limelight'"));
for (const label of ['app_label', 'app_label_root', 'app_label_game']) {
    assert.equal([...gradle.matchAll(new RegExp(`resValue "string", "${label}", "NOUS"`, 'g'))].length, 2);
}
assert(read('app/src/main/java/com/limelight/Game.java').includes('CLIPBOARD_IDENTIFIER = "ArtemisStreaming"'));
assert(read('app/src/main/java/com/limelight/utils/ShortcutHelper.java').includes('# Generated by NOUS for Android'));
assert(read('app/src/main/java/com/limelight/preferences/StreamSettings.java').includes('"nous_logs.txt"'));
assert(read('app/src/main/java/com/limelight/nvstream/jni/MoonBridge.java').includes('System.loadLibrary("moonlight-core")'));
assert(read('app/src/main/res/values/nous_refinement.xml').includes('Based on Artemis and Moonlight Android.'));
console.log(`PASS: ${checked} string resource files, store metadata, app labels, identity, JNI and attribution`);
